// Recursive type that widens literal strings and removes readonly
// so that both the CS and EN dictionaries satisfy the same shape.
type Widen<T> =
  T extends string ? string :
  T extends number ? number :
  T extends boolean ? boolean :
  T extends readonly (infer U)[] ? readonly Widen<U>[] :
  T extends Record<string, unknown> ? { readonly [K in keyof T]: Widen<T[K]> } :
  T

export type Dictionary = Widen<typeof cs>
